"""یک تعریف، برای همهٔ آزمون‌ها: «شمارِ خط» یعنی همان چیزی که `wc -l` می‌گوید.

پیش‌تر دو تعریف در مخزن بود: `test_file_sizes.py` با `len(text.split('\n'))`
(یک بیشتر برای فایلِ پایان‌یافته با نویسهٔ خطِ تازه) و مستندات با `wc -l`. نتیجه
این شد که `engine.dart` در یک جا ۱۸۸ بود و در جای دیگر ۱۸۹ و `chip_texts.dart`
۵۵ در برابر ۵۶. عددِ متناقض، عددِ بی‌فایده است؛ حالا فقط این تابع مرجع است.
"""


def line_count(path):
    with open(path, encoding='utf-8') as f:
        return f.read().count('\n')
