// ---- برداشت وکیل

List<String> partnerRecap(CaseFile f) => [
      'با شریکتان اختلاف دارید',
      if (f.yes('written')) 'شراکت‌نامهٔ کتبی دارید',
      if (f.no('written')) 'شراکت شفاهی بوده',
      if (f.eq('lease', 'both')) 'اجاره‌نامه به نام هر دوی شماست',
      if (f.eq('lease', 'his')) 'اجاره‌نامه به نام اوست',
      if (f.eq('lease', 'mine')) 'اجاره‌نامه به نام شماست',
      if (f.eq('goal', 'exit')) 'می‌خواهید از شراکت بیرون بیایید',
      if (f.eq('goal', 'stay')) 'می‌خواهید شراکت بماند و حقتان را بگیرید',
    ];

