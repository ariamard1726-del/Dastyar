    }
    if (f.eq('aim', 'damage')) {
      return '$lead دعوای خسارت به مدرک بسته است: باید نشان بدهید خرابی از کوتاهی یا زیاده‌روی مستأجر بوده، نه فرسودگی عادی [[civil:493]]. با نظر کارشناسِ تأمین دلیل، دست شما پر است؛ بدون آن، سخت.';
    }
    if (f.eq('aim', 'breach')) {
      return '$lead همه‌چیز به متن اجاره‌نامه برمی‌گردد: اگر شرطی که می‌گویید در قرارداد نوشته شده و تخلف را بتوانید نشان دهید، حق فسخ دارید [[civil:496]]؛ اگر نوشته نشده، کار سخت می‌شود.';
    }
    return '$lead اگر مدت تمام شده و اجاره‌نامهٔ کتبیِ شاهددار دارید، دستور تخلیه از سریع‌ترین و مطمئن‌ترین راه‌هاست [[landlord_tenant:3]]؛ تنها گره‌اش آماده‌بودن ودیعهٔ مستأجر است [[landlord_tenant:4]]. پیش از پایان مدت، بدون شرط فسخ در قرارداد، شانس کمی دارید.';
  }
  if (f.eq('matter', 'raise')) {
    return '$lead تا پایان مدت قرارداد حق با شماست و او نمی‌تواند مبلغ را عوض کند [[civil:219]]. بعد از پایان مدت، قانون او را به تمدید مجبور نمی‌کند؛ پس قوت شما به تاریخ پایان اجاره‌نامه و به مذاکره بسته است.';
  }
  if (_ordered(f)) {
    return '$lead اگر مدت قرارداد واقعاً تمام شده، جلوی خودِ دستور تخلیه را به‌سختی می‌شود گرفت [[landlord_tenant:3]]؛ ولی دو اهرم دارید: ودیعه‌ای که تا پس داده نشود تخلیه اجرا نمی‌شود [[landlord_tenant:4]]، و شکایت به دادگاه اگر دربارهٔ قرارداد حقی دارید [[landlord_tenant:5]].';
  }
  if (f.eq('matter', 'evict')) {
    return '$lead بیرون‌کردنِ خودسرانه هیچ پشتوانه‌ای ندارد و تا دستور مرجع رسمی نباشد، دست شما بالاتر است. ولی اگر مدت قرارداد تمام شده باشد، او می‌تواند دستور تخلیه بگیرد [[landlord_tenant:3]] و آن‌وقت تکیهٔ شما به پس‌گرفتن هم‌زمان ودیعه است [[landlord_tenant:4]].';
  }
  if (f.eq('matter', 'deliver')) {
    return '$lead تحویل ملک نخستین تعهد موجر است [[civil:476]] و اگر اجاره‌نامه و رسید پرداخت‌هایتان را داشته باشید، حرف شما پشتوانهٔ محکمی دارد. تنها چیزی که کار را کُند می‌کند زمان دادرسی است؛ برای همین اگر جای دیگری می‌توانید پیدا کنید، فسخ و پس‌گرفتن ودیعه معمولاً زودتر به نتیجه می‌رسد.';
  }
  if (f.eq('matter', 'repair')) {
    return '$lead اگر در اجاره‌نامه تعمیرات به عهدهٔ شما گذاشته نشده باشد و خرابی را مستند کرده باشید، حرف شما پشتوانهٔ روشن قانونی دارد [[civil:486]].';
  }
  if (f.eq('matter', 'leave')) {
    return '$lead بدون رضایت موجر یا حق فسخ در قرارداد، قانون طرف شما نیست، چون اجاره برای هر دو طرف الزام‌آور است [[civil:219]]. بیشترین شانس شما در توافق است [[civil:283]]؛ پس با پیشنهاد مستأجر جایگزین سراغش بروید.';
  }
  final plus = <String>[];
  final minus = <String>[];
  if (f.yes('vacated')) {
    plus.add('ملک را تحویل داده‌اید و او دیگر دلیلی برای نگه‌داشتن پول ندارد');
  }
  if (f.yes('ended')) plus.add('مدت قرارداد تمام شده است');
  if (f.yes('contract')) plus.add('قرارداد کتبی دارید');
  if (f.no('contract')) {
    minus.add(
        'قرارداد کتبی ندارید و باید پرداخت ودیعه را با رسید، پیام یا شاهد ثابت کنید');
  }
  if (f.no('ended')) minus.add('مدت قرارداد هنوز تمام نشده');
  if (f.covered.contains('damage')) {
    minus.add(
        'او ادعای خسارت دارد که اگر دادخواست بدهد، ممکن است بخشی از پول تا روشن‌شدن آن ادعا نگه داشته شود');
  }
  final sb = StringBuffer(
      'قول قطعی نمی‌دهم (هیچ وکیل درستی نمی‌دهد)، ولی ارزیابی من این است: دعوای استرداد ودیعه از محکم‌ترین دعواهاست، چون قانون صریح است [[landlord_tenant:4]].');
  if (plus.isNotEmpty) sb.write('\nنقاط قوت شما: ${plus.join('؛ ')}.');
  if (minus.isNotEmpty) sb.write('\nنقطهٔ ضعف: ${minus.join('؛ ')}.');
  if (plus.isEmpty && minus.isEmpty) {
    sb.write(
        '\nاگر پرداخت ودیعه و تخلیه را بتوانید نشان دهید، احتمال موفقیت بالاست.');
  }
  return sb.toString();
}

String _rentWhere(CaseFile f) {
  if (f.eq('role', 'landlord')) {
    if (f.eq('aim', 'unpaid') || f.eq('aim', 'damage')) {
      return moneyForum(_rentSum(f));
    }
    return 'درخواست تخلیه را از طریق دفتر خدمات الکترونیک قضایی ثبت می‌کنید و مرجع رسیدگی «دادگاه صلحِ» محل ملک است [[dispute_councils:12]].';
  }
  if (_shop(f) && f.covered.contains('goodwill')) {
    return 'دعوای سرقفلی و حق کسب و پیشه از صلاحیت دادگاه صلح بیرون است و در «دادگاه عمومی حقوقیِ» محل ملک رسیدگی می‌شود [[dispute_councils:12]]؛ ثبتش از طریق دفتر خدمات الکترونیک قضایی است.';
  }
  return _rentDeposit(f) ? moneyForum(f.n('amount')) : _rentPeace;
}

