/// مرجع صالح دعوای مالی بر پایهٔ مبلغ.
String moneyForum(int? toman) {
  const tail =
      ' دعوا اصولاً در حوزهٔ محل اقامت طرف مقابل ثبت می‌شود [[civil_procedure:11]] و ثبتش از طریق دفتر خدمات الکترونیک قضایی است.';
  if (toman == null) {
    return 'مرجع رسیدگی به مبلغ بستگی دارد: تا یک میلیارد ریال (۱۰۰ میلیون تومان) «دادگاه صلح» و بیشتر از آن «دادگاه عمومی حقوقی» [[dispute_councils:12]].$tail';
  }
  if (toman <= 100000000) {
    return 'چون مبلغ ${Sense.toman(toman)} است و از نصاب یک میلیارد ریال بیشتر نیست، مرجع رسیدگی «دادگاه صلح» است [[dispute_councils:12]].$tail';
  }
  return 'چون ${Sense.toman(toman)} از نصاب دادگاه صلح (یک میلیارد ریال) بیشتر است، پرونده به «دادگاه عمومی حقوقی» می‌رود [[dispute_councils:12]] [[civil_procedure:10]].$tail';
}

