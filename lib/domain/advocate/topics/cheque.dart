String? _chequeRole(String n) {
  if (Sense.has(n,
      'خودم (?:چک[^ ]* )?(?:رو )?(?:کشیدم|دادم|نوشتم|صادر)|چک[^ ]* (?:رو |را )?(?:کشیدم|نوشتم|صادر کردم)|صادرکننده (?:ام|منم|هستم|خودمم)|چک دادم|حسابم (?:خالی|پول نداشت|موجودی نداشت)|نتونستم پاس|نمیتونم پاسش|پاسش کنم|چکم دست|چکم (?:رو )?(?:برگشت زد|گذاشت(?:ه)? اجرا)|برام اجرائیه')) {
    return 'issuer';
  }
  if (Sense.has(n,
      'چک[^ ]* (?:رو |را )?(?:گرفتم|گرفته بودم|داد(?:ه)? بهم|بهم داد)|ازش چک|چک(?:ی)? (?:[^ ]+ ){0,3}(?:دارم|دستمه|دست منه)|چکش|چک طرف|چک مشتری|بهم چک داد|دارنده (?:ام|هستم)|چک(?:ی)? (?:که )?(?:ازش|بهم)|(?:بذارم|بگذارم|میذارم) اجرا|اجرا (?:بذارم|بگذارم)|برگشت (?:زدم|بزنم)|گواهی عدم پرداخت(?: رو)? گرفتم|شکایت کیفری کنم|پاسش نمیکنه|پولمو نمیده')) {
    return 'holder';
  }
  return null;
}

String? _chequeKind(String n) {
  if (Sense.has(n, 'ضمانت|تضمین|امانی|امانت|سفید امضا|حسن انجام')) return 'guarantee';
  if (Sense.has(n, 'وعده ?دار|مدت ?دار|تاریخ[^ ]* (?:مال|برای) (?:بعد|ماه)|برای (?:چند|یه|دو|سه) ماه بعد')) return 'postdated';
  if (Sense.has(n, 'به روز|روز بود|همون روز|تاریخ روز')) return 'day';
  return null;
}

String _chequeKindEffect(CaseFile f) {
  final issuer = f.eq('role', 'issuer');
  switch (f.get('kind')) {
    case 'guarantee':
      return issuer
          ? 'اینکه چک بابت ضمانت بوده، برگ مهمی به نفع شماست:\n'
              '• از جهت کیفری: اگر ثابت شود چک بابت تضمین بوده، حتی وقتی روی خود چک چیزی ننوشته باشید، قابل تعقیب کیفری نیستید [[cheque:13]].\n'
              '• از جهت اجرائیه: دادگاه فقط وقتی اجرائیه نمی‌دهد که تضمینی‌بودن «در متن خود چک» نوشته شده باشد [[cheque:23]]. پس اگر روی چک قید نشده، دارنده می‌تواند اجرائیه بگیرد و طرحِ دعوای «تضمینی‌بودن» از طرف شما خودبه‌خود جلوی اجرا را نمی‌گیرد؛ مگر دادگاه با گرفتن تأمین، قرار توقف اجرا بدهد [[cheque:23]].\n'
              'پس کار شما این است: قراردادی که نشان می‌دهد چک ضمانت بوده را آماده کنید و اگر تعهدتان را انجام داده‌اید (یا هنوز موعدش نرسیده)، دادخواست «استرداد چک» بدهید و هم‌زمان توقف عملیات اجرایی را بخواهید.'
          : 'چک تضمینی قابل شکایت کیفری نیست [[cheque:13]]. اجرائیهٔ سریع دادگاه هم فقط وقتی صادر نمی‌شود که تضمینی‌بودن «در متن خود چک» نوشته شده باشد [[cheque:23]]؛ اگر روی چک چیزی قید نشده، می‌توانید اجرائیه بگیرید، ولی صادرکننده می‌تواند با قرارداد ثابت کند چک ضمانت بوده و جلوی اجرا را بگیرد. در هر حال باید بتوانید نشان دهید تعهدی که چک ضامنش بوده انجام نشده است.';
    case 'postdated':
      return issuer
          ? 'چون چک وعده‌دار بوده، از جهت کیفری قابل تعقیب نیستید [[cheque:13]]؛ ولی بدهی مالی سر جایش است و دارنده می‌تواند اجرائیه بگیرد [[cheque:23]].'
          : 'چک وعده‌دار قابل شکایت کیفری نیست [[cheque:13]]، ولی حق مالی شما کاملاً سر جایش است و اجرائیهٔ دادگاه برایش صادر می‌شود [[cheque:23]].';
    default:
      return issuer
          ? 'چون چک به تاریخ روز بوده، هم خطر کیفری هست [[cheque:7]] هم اجرائیه [[cheque:23]]؛ پرداخت یا توافق با دارنده پیش از شکایت، جلوی تعقیب را می‌گیرد [[cheque:9]].'
          : 'چون چک به تاریخ روز بوده، هر دو راه کیفری و اجرائیه برایتان باز است [[cheque:7]] [[cheque:23]]؛ فقط مهلت شش‌ماههٔ شکایت را از دست ندهید [[cheque:11]].';
  }
}

String _chequeRoutes(CaseFile f) {
  final kind = f.get('kind');
  final late = (f.n('since') ?? 0) > 6;
  final sb = StringBuffer(
      'برای وصول چک سه راه دارید و هر کدام به درد یک وضعیت می‌خورد:\n'
      '۱) اجرائیه از دادگاه: با گواهی عدم پرداخت، بدون دادرسی طولانی اجرائیه می‌گیرید و صادرکننده ۱۰ روز فرصت پرداخت دارد؛ وگرنه اموالش توقیف می‌شود [[cheque:23]]. شرطش این است که چک مشروط، بابت تضمین یا مسدودشده نباشد.\n'
      '۲) شکایت کیفری: ابزار فشار است (حبس و محرومیت از دسته‌چک) [[cheque:7]]، ولی فقط وقتی ممکن است که چک وعده‌دار، سفیدامضا، مشروط یا بابت تضمین نباشد [[cheque:13]] و مهلت‌ها رعایت شده باشد: ارائه به بانک تا ۶ ماه از تاریخ چک و شکایت تا ۶ ماه از گواهی عدم پرداخت [[cheque:11]].\n'
      '۳) دادخواست حقوقی: کندتر است، اما همیشه باز است و خسارت تأخیر تأدیه و هزینه‌ها را هم می‌شود با آن گرفت [[civil_procedure:522]].');
  sb.write('\n\nنظر من برای وضعیت شما: ');
  if (kind == 'guarantee') {
    sb.write(
        'چون چک بابت ضمانت/امانت بوده، راه کیفری بسته است [[cheque:13]] و اگر تضمینی‌بودن روی خود چک نوشته شده باشد اجرائیهٔ سریع هم نمی‌دهند [[cheque:23]]؛ راه مطمئن، دادخواست حقوقی است و باید ثابت کنید تعهدی که چک ضامنش بوده انجام نشده است.');
  } else if (kind == 'postdated') {
    sb.write(
        'چون چک وعده‌دار بوده، شکایت کیفری جواب نمی‌دهد [[cheque:13]]؛ بهترین راه «اجرائیه از دادگاه» است [[cheque:23]] و هم‌زمان درخواست توقیف اموال.');
  } else if (late) {
    sb.write(
        'چون از مهلت شش‌ماههٔ شکایت کیفری گذشته است [[cheque:11]]، سراغ اجرائیهٔ دادگاه بروید [[cheque:23]]؛ حق مالی شما با گذشت این مهلت از بین نمی‌رود.');
  } else {
    sb.write(
        'اگر هدفتان «زودتر رسیدن به پول» است، اجرائیهٔ دادگاه معمولاً سریع‌ترین راه است [[cheque:23]]. شکایت کیفری را وقتی کنارش بگذارید که چک به تاریخ روز صادر شده و هنوز در مهلت شش‌ماهه هستید؛ بیشتر چک‌های بازار وعده‌دارند و در آن‌ها راه کیفری بسته است [[cheque:13]].');
  }
  return sb.toString();
}

String _chequeIssuer(CaseFile f) {
  return 'وقتی صادرکننده شما هستید، باید هم خطر را بشناسید هم راه مهارش را:\n'
      '• خطر مالی: دارنده می‌تواند با گواهی عدم پرداخت اجرائیه بگیرد؛ از ابلاغ آن فقط ۱۰ روز برای پرداخت یا توافق فرصت دارید و بعد حساب‌ها و اموالتان توقیف می‌شود [[cheque:23]].\n'
      '• خطر کیفری: اگر چک به تاریخ روز و بدون شرط بوده، با شکایت دارنده حبس و محرومیت از دسته‌چک در کار است [[cheque:7]]. اما اگر چک وعده‌دار، سفیدامضا، مشروط یا بابت تضمین بوده، اصلاً قابل تعقیب کیفری نیست [[cheque:13]].\n'
      '• راه مهار: اگر پیش از شکایت، وجه چک را بپردازید یا با دارنده ترتیب پرداخت بدهید، تعقیب نمی‌شوید [[cheque:9]]؛ بعد از شکایت هم با پرداخت یا رضایت او، پرونده در هر مرحله‌ای بسته می‌شود [[cheque:12]].\n'
      '• اگر واقعاً توان پرداخت یک‌جا ندارید، در برابر اجرائیه می‌شود دادخواست اعسار و تقسیط داد؛ اگر ظرف ۳۰ روز از ابلاغ اجرائیه و با فهرست اموال باشد، حبس هم نمی‌شوید [[financial_sentences:3]] [[financial_sentences:11]].\n'
      'توصیهٔ عملی من: قبل از هر چیز با دارنده حرف بزنید و هر توافقی کردید کتبی کنید؛ برای او هم گرفتن پول قسطی بهتر از دوندگی دادگاه است.';
}

