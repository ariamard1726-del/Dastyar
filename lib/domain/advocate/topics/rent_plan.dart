        '۲) پیام‌ها و تهدیدهایش را نگه دارید.\n'
        '۳) تا وقتی مدت قرارداد تمام نشده یا دستور تخلیه از مرجع رسمی نیامده، اجباری به رفتن ندارید [[landlord_tenant:3]].\n'
        '۴) اگر دستور تخلیه آمد، تحویل ملک موکول به پس‌گرفتن ودیعه است [[landlord_tenant:4]].';
  }
  if (f.eq('matter', 'deliver')) {
    return 'برای تحویل‌گرفتن ملک، پیشنهاد من:\n'
        '۱) تا تحویل نگرفته‌اید پول تازه‌ای ندهید و رسید هرچه داده‌اید (ودیعه، اجاره، کمیسیون بنگاه) را نگه دارید.\n'
        '۲) با اظهارنامهٔ رسمی تحویل ملک را بخواهید و تاریخ بگذارید [[civil_procedure:156]].\n'
        '۳) اگر تحویل نداد، دو راه دارید: «الزام به تحویل مورد اجاره» را از دادگاه بخواهید، یا اگر واداشتنش شدنی نبود اجاره را فسخ کنید و ودیعه را پس بگیرید [[civil:476]].\n'
        '۴) برای روزهایی که ملک در اختیارتان نبوده، بخواهید اجاره‌ای حساب نشود؛ اجاره در برابرِ استفاده از ملک است.\n'
