        '۳) برای دورهٔ بعد مذاکره کنید و هر توافقی را کتبی و با تاریخ بنویسید.\n'
        '۴) اگر به توافق نرسیدید، با پایان مدت ملک را تحویل می‌دهید و او هم باید هم‌زمان ودیعه را پس بدهد [[landlord_tenant:4]].';
  }
  if (_ordered(f)) {
    return 'برای دستور تخلیه‌ای که آمده، به این ترتیب عمل کنید:\n'
        '۱) تاریخ ابلاغ و مهلتش را روی برگه ببینید و همان روز به شعبهٔ صادرکننده یا واحد اجرا بروید.\n'
        '۲) بگویید ودیعه‌تان را نگرفته‌اید؛ تا پس داده یا به اجرا سپرده نشود، تخلیه انجام نمی‌شود [[landlord_tenant:4]].\n'
        '۳) اگر مدت قرارداد تمام نشده یا تمدید شده، با مدرکش (اجاره‌نامه، رسید اجاره‌های بعدی) به دادگاه شکایت کنید [[landlord_tenant:5]].\n'
