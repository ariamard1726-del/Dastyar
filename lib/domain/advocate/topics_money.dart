    sb.write(
        'اگر هدفتان «زودتر رسیدن به پول» است، اجرائیهٔ دادگاه معمولاً سریع‌ترین راه است [[cheque:23]]. شکایت کیفری را وقتی کنارش بگذارید که چک به تاریخ روز صادر شده و هنوز در مهلت شش‌ماهه هستید؛ بیشتر چک‌های بازار وعده‌دارند و در آن‌ها راه کیفری بسته است [[cheque:13]].');
  }
  return sb.toString();
}

