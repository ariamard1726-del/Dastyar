String? _rentRole(String n) {
  // ۱) خودش گفته کدام طرف است.
  if (Sense.has(n,
      'من موجر|موجر هستم|صاحبخونه هستم|مالک هستم|من مالک|من صاحبخونه|اجاره دادم|اجاره داده ام|به مستاجر|خونه ام رو (?:اجاره|رهن) داد')) {
    return 'landlord';
  }
  if (Sense.has(n, 'من مستاجر|مستاجر هستم|مستاجر(?:م|ام) (?:و|که|هستم)|اجاره نشین')) {
    return 'tenant';
  }
  // ۲) از طرف مقابل حرف می‌زند.
  if (Sense.has(n, 'صاحبخونه|موجر|پول پیشم|پول رهنم|ودیعه ام|رهنم ')) {
    return 'tenant';
  }
  if (Sense.has(n,
      'مستاجر[^ ]* (?:[^ ]+ ){0,9}(?:نمیده|نداده|نمیکنه|نکرده|نمیشه|نمیره|نمیپردازه|خراب کرد|رفته|مونده|نشسته)')) {
    return 'landlord';
  }
  if (Sense.has(n, 'مستاجرم|پول پیش|ودیعه')) return 'tenant';
  return null;
}

