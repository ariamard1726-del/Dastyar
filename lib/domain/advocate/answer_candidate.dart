part of 'advocate.dart';

// یک پاسخِ ممکن برای همین پیام، و داوری که میانشان انتخاب می‌کند.
//
// پیش‌تر ترتیبِ پاسخ‌ها فقط از ترتیبِ `if`های داخلِ `_reply` پیدا می‌شد: برای
// فهمیدنِ اینکه «ایمنی پیش از موضوع است یا بعدش» باید دویست خط کد خوانده
// می‌شد. حالا هر پاسخ یک ورودیِ نام‌دار در یک فهرست است و داور، **اولین**
// ورودی‌ای که جواب بدهد را برمی‌گرداند.
//
// این «امتیازدهی» نیست: داور هیچ ورودی‌ای را دوباره وزن نمی‌کند، چون ترتیبِ
// فعلی در چند جا خودش تصمیم است (ایمنی پیش از موضوع، اصلاحِ کاربر پیش از
// بازکردنِ پرونده). ترتیب = اولویت، و عوض‌کردنش باید آگاهانه باشد، نه
// نتیجهٔ یک عدد.

/// یک پاسخِ ممکن، با نامی که در گفتگو و در آزمون قابلِ ارجاع باشد.
class AnswerCandidate {
  const AnswerCandidate(this.name, this.build);

  /// نامِ کوتاهِ مسیر؛ در مستندات و آزمون‌ها همین نام به‌کار می‌رود.
  final String name;

  /// پاسخ را می‌سازد؛ `null` یعنی «این پیام مالِ من نیست».
  final AdvocateReply? Function() build;
}

/// داورِ فهرست: اولین کاندیدی که پاسخ بدهد برنده است.
class AnswerArbiter {
  const AnswerArbiter();

  AdvocateReply? pick(Iterable<AnswerCandidate> candidates) {
    for (final c in candidates) {
      final r = c.build();
      if (r != null) return r;
    }
    return null;
  }
}
