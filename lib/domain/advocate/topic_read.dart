/// نتیجهٔ «خواندنِ موضوع» از یک پیام: بهترین موضوع، امتیازش و امتیازِ همه.
///
/// این یک **مقدار** است، نه رفتار. `_reply` آن را یک بار می‌سازد و به بخش‌های
/// بعدی می‌دهد؛ پیش‌تر همین حلقه‌ها وسطِ تصمیم‌گیری نوشته شده بودند و برای
/// فهمیدنِ «چرا این پیام پرونده باز کرد» باید هم محاسبه و هم ده شرطِ بعدش
/// خوانده می‌شد.
class TopicRead {
  const TopicRead({this.best, required this.bestScore, required this.scores});

  /// بهترین موضوعِ این پیام؛ `null` یعنی هیچ موضوعی نشانه ندارد.
  final Topic? best;

  /// امتیازِ [best]. صفر یعنی هیچ نشانه‌ای نبود.
  final int bestScore;

  /// امتیازِ همهٔ موضوع‌ها، برای پاسخ‌هایی که باید «موضوعِ کنارِ هم» را ببینند.
  final Map<String, int> scores;

  /// آیا موضوعی با نشانهٔ کافی پیدا شد؟ (همان آستانهٔ بازکردنِ پرونده.)
  bool get opens => best != null && bestScore >= topicOpenMin;
}
