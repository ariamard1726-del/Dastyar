List<String> accusedRecap(CaseFile f) {
  const names = {
    'fraud': 'کلاهبرداری',
    'trust': 'خیانت در امانت',
    'insult': 'توهین',
    'threat': 'تهدید',
    'assault': 'ضرب‌وجرح',
    'theft': 'سرقت',
    'defame': 'افترا',
  };
  final c = names[f.get('charge')];
  return [
    if (c != null) 'از شما به اتهام $c شکایت شده',
    if (f.eq('charge', '?')) 'نمی‌دانید شکایت بابت چیست',
    if (f.yes('notice')) 'احضاریه یا ابلاغیه به دستتان رسیده',
    if (f.no('notice')) 'هنوز ابلاغ رسمی نیامده',
    if (f.yes('docs')) 'برای آن ماجرا مدرک دارید',
    if (f.no('docs')) 'نوشته یا مدرکی در کار نیست',
  ];
}

