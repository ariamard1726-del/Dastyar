  /// پاسخهای کوتاه تأییدی در میانهٔ جلسهٔ حقوقی نباید بلعیده شوند؛
  /// آنجا «بله ممنون» یعنی پاسخ به اسلات قبلی، نه گفتگوی کوتاه.
  static const List<String> _confirmationWords = <String>[
