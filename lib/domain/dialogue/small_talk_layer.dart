  static bool _startsWithConfirmation(String phrase) =>
      _confirmationWords.any((w) => phrase == w || phrase.startsWith('$w '));

  /// مسیریابی پیام. `null` یعنی «این پیام به جریان حقوقی واگذار شود».
  ///
  /// اگر [rnd] داده شود، از میان گزینههای متنوع یکی به تصادف انتخاب
  /// میشود تا تکرار پاسخها رباتیک نباشد؛ بدون آن همیشه گزینهٔ نخست
  /// (نسخهٔ مرجع و قطعی) برگردانده میشود تا رفتار تستها پایدار بماند.
  SmallTalkReply? tryHandle(
    String rawText, {
    bool hasActiveLegalContext = false,
    Random? rnd,
  }) {
    final phrase = PersianText.phrase(rawText);
    if (phrase.isEmpty) return null;

    // ۱) هیچ پیام حقوقی (حتی با سلام شروع شده) وارد این لایه نمیشود.
    if (_hasLegalSignalIn(phrase)) return null;

    // ۲) در جریان حقوقی فعال، پاسخهای تأییدی به اسلاتها حفظ میشوند.
    if (hasActiveLegalContext && _startsWithConfirmation(phrase)) return null;

    final intent = _classify(phrase);
    if (intent == null) return null;

    // پیامهای ترکیبی رایج: «سلام، خوبی؟» یا «ممنون، خداحافظ». پاسخ
    // باید هر دو بخش پیام را تصدیق کند تا گفتگو طبیعی به نظر برسد.
    final bool withGreeting =
        intent == SmallTalkIntent.howAreYou && _greetingRe.hasMatch(phrase);
    final bool withThanks =
        intent == SmallTalkIntent.farewell && _thanksRe.hasMatch(phrase);

    return SmallTalkReply(
      intent: intent,
      text: _replyFor(intent, hasActiveLegalContext, rnd,
          withGreeting: withGreeting, withThanks: withThanks),
      chips: hasActiveLegalContext ? activeSessionChips : defaultIntakeChips,
    );
  }

  static SmallTalkIntent? _classify(String phrase) {
    // ترتیب اهمیت: ناسزا و ناراحتی زودتر از احوالپرسی پاسخ میگیرند تا
    // «لعنتی سلام» یا «سلام حالم بده» به پیام خشک سلام تقلیل نیابد.
    if (_profanityRe.hasMatch(phrase)) return SmallTalkIntent.profanity;
    if (_distressRe.hasMatch(phrase)) return SmallTalkIntent.distress;
    if (_farewellRe.hasMatch(phrase)) return SmallTalkIntent.farewell;
    // اظهار محبت پیش از احوال‌پرسی بررسی میشود تا «رفیق خوبی هستی» به
    // خاطر واژهٔ «خوبی» به احوال‌پرسی تقلیل نیابد.
    if (_affectionRe.hasMatch(phrase)) return SmallTalkIntent.affection;
    // احوال‌پرسی پیش از سلام بررسی میشود تا «سلام خوبی؟» پاسخ هر دو
    // بخش پیام را بگیرد، نه فقط بخش سلام.
    if (_howAreYouRe.hasMatch(phrase)) return SmallTalkIntent.howAreYou;
    if (_greetingRe.hasMatch(phrase)) return SmallTalkIntent.greeting;
    if (_thanksRe.hasMatch(phrase)) return SmallTalkIntent.thanks;
    if (_identityRe.hasMatch(phrase)) return SmallTalkIntent.identity;
    if (_capabilitiesRe.hasMatch(phrase)) return SmallTalkIntent.capabilities;
    if (_botQuestionRe.hasMatch(phrase)) return SmallTalkIntent.botQuestion;
    if (_praiseRe.hasMatch(phrase)) return SmallTalkIntent.praise;
    if (_userApologyRe.hasMatch(phrase)) return SmallTalkIntent.userApology;
    if (_confusionRe.hasMatch(phrase)) return SmallTalkIntent.confusion;
    if (_repeatRequestRe.hasMatch(phrase)) {
      return SmallTalkIntent.repeatRequest;
    }
    if (_criticismRe.hasMatch(phrase)) return SmallTalkIntent.criticism;
    if (_privacyConcernRe.hasMatch(phrase)) {
      return SmallTalkIntent.privacyConcern;
    }
    if (_languageQuestionRe.hasMatch(phrase)) {
      return SmallTalkIntent.languageQuestion;
    }
    if (_fineAnswerRe.hasMatch(phrase)) return SmallTalkIntent.fineAnswer;
    if (_metaNextStepRe.hasMatch(phrase)) return SmallTalkIntent.metaNextStep;
    if (_offTopicRe.hasMatch(phrase)) return SmallTalkIntent.offTopic;
    return null;
  }

